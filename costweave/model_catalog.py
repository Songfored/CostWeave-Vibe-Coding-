def _model(model_id: str, name: str, provider: str, specialty: str,
           capabilities: dict[str, float], *, tier: str, reasoning: float,
           speed: float, reliability: float, context: int, max_output: int,
           input_price: float, output_price: float,
           cached_price: float | None = None,
           modalities: tuple[str, ...] = ("text",),
           tools: tuple[str, ...] = ("function_calling", "structured_output"),
           strengths: tuple[str, ...] = (), limitations: tuple[str, ...] = (),
           local: bool = False, currency: str = "USD", preview: bool = False,
           routable: bool = True, confidence: float = .90,
           source_url: str | None = None) -> WorkerProfile:
    return WorkerProfile(
        id=model_id, model_id=model_id, name=name, provider=provider,
        specialty=specialty, capabilities=capabilities, cost_per_task=0.0,
        latency_factor=float(max(.35, 1.55 - speed)), reliability=float(reliability),
        local=local, tier=tier, reasoning=float(reasoning), speed=float(speed),
        context_window=context, max_output_tokens=max_output,
        input_price_per_mtok=float(input_price),
        cached_input_price_per_mtok=(float(cached_price) if cached_price is not None else None),
        output_price_per_mtok=float(output_price), pricing_currency=currency,
        modalities=list(modalities), tools=list(tools), strengths=list(strengths),
        limitations=list(limitations), source_url=source_url or SOURCES.get(provider, ""),
        verified_at=SNAPSHOT_DATE, preview=preview, routable=routable,
        data_confidence=confidence,
    )


